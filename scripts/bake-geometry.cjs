// Run after changing geometry-source.ts. Browser SVG metrics are an authoring
// dependency only; production consumes a 34.6 kB quantized topology asset.
const fs = require('node:fs');
const {buildSync} = require('esbuild');
const {chromium} = require('@playwright/test');
(async () => {
  const js = buildSync({stdin: {contents: "import {buildGeometry} from './src/data/geometry-source'; buildGeometry().then(poses => globalThis.__nrthPoses = poses);", resolveDir: process.cwd(), loader: 'ts'}, bundle: true, write: false, format: 'iife', target: 'es2022'}).outputFiles[0].text;
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage']});
  try {
    const page = await browser.newPage();
    page.on('pageerror', error => {throw error;});
    await page.goto('about:blank'); await page.addScriptTag({content: js});
    await page.waitForFunction(() => globalThis.__nrthPoses);
    const poses = await page.evaluate(() => globalThis.__nrthPoses);
    const data = new Int16Array(poses.flat(3).map(n => Math.round(n * 1000)));
    fs.writeFileSync('src/data/geometry-baked.ts', '// Generated by npm run bake:geometry. 10 poses × 4 strands × 192 points × xyz.\nexport const geometry = ' + JSON.stringify(Buffer.from(data.buffer).toString('base64')) + ';\n');
    console.log('Baked ' + data.byteLength + ' bytes of topology-preserving geometry.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exit(1);});
