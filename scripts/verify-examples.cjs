/* Focused interruption / native-input coverage for the finite SVG example director. */
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const base=process.env.NRTH_TEST_URL||'http://127.0.0.1:4173';
const artifact=path.join(process.cwd(),'artifacts','next-stage','examples');
fs.mkdirSync(artifact,{recursive:true});
let checks=0;
const check=(value,message)=>{if(!value)throw new Error(message);checks++;};
const pose=page=>page.locator('[data-worked-example] [data-example-node]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('transform')).join('|'));
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 for(const slug of ['tms','health','chemicals']){
  await page.goto(base+'/projects/nrth-'+slug);
  const root=page.locator('[data-worked-example]');
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]')?.classList.contains('is-enhanced'));
  await root.locator('svg').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]').dataset.exampleVisible==='true');
  const initial=await pose(page);
  await page.evaluate(()=>document.querySelectorAll('[data-scenario-choice]')[1].click());
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]').dataset.exampleSettled==='false');
  await page.waitForTimeout(240);
  const intermediate=await pose(page);
  check(intermediate!==initial,slug+' moves the existing node population during a scenario change.');
  check(await root.getAttribute('data-example-settled')==='false',slug+' retains a finite continuous transition.');
  await page.evaluate(()=>document.querySelectorAll('[data-scenario-choice]')[0].click());
  await page.waitForTimeout(35);
  const reverse=await pose(page);
  check(reverse!==initial,slug+' reverses from its current pose instead of snapping to its destination.');
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]').dataset.exampleSettled==='true');
  check(await pose(page)===initial,slug+' finishes at the exact initial geometry after reversal.');
  await page.evaluate(()=>{document.querySelectorAll('[data-scenario-choice]')[2].click();document.querySelectorAll('[data-scenario-choice]')[1].click();});
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]').dataset.exampleSettled==='true');
  check(await root.getAttribute('data-example-state')==='1',slug+' respects the final input in an interrupted sequence.');
  check(await root.locator('[data-example-node][data-status=pending], [data-example-node][data-status=held]').count()>0,slug+' attaches uncertainty to actual parts.');
  const toggle=root.locator('[data-example-dependencies-toggle]');
  if(await toggle.getAttribute('aria-pressed')==='false')await toggle.click();
  check(await root.locator('[data-example-node][data-dependency=true]:visible').count()===2,slug+' exposes two named downstream dependencies.');
  const part=root.locator('[data-example-part-record]').nth(2),summary=part.locator('summary');
  if(!await part.evaluate(node=>node.open)){await summary.focus();await page.keyboard.press('Enter');}
  await page.waitForFunction(()=>document.querySelector('[data-worked-example]').dataset.examplePart===document.querySelectorAll('[data-example-part-record]')[2].dataset.examplePartRecord);
  check(await root.locator('[data-example-node].is-inspected').count()===1,slug+' maps keyboard inspection to one real part.');
  check(await root.locator('[data-example-edge].is-inspected').count()>0,slug+' highlights the edges incident to that part.');
  await root.locator('.ve-technical > summary').click();
  check(await root.locator('.ve-technical-content').isVisible(),slug+' exposes application-specific technical scope natively.');
  await root.screenshot({path:path.join(artifact,slug+'.png')});
 }
 const native=await browser.newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});
 await native.goto(base+'/projects/nrth-tms');
 check(await native.locator('[data-scenario-panel]:visible').count()===3,'No JavaScript retains all three scenario contexts.');
 check(await native.locator('[data-example-record]:visible').count()===3,'No JavaScript retains all worked consequences.');
 check(await native.locator('[data-example-part-record]:visible').count()===6,'No JavaScript retains every responsibility record.');
 await native.locator('.ve-technical > summary').click();
 check(await native.locator('.ve-technical-content').isVisible(),'Technical notes work without JavaScript.');
 const motion=await browser.newPage({reducedMotion:'reduce',viewport:{width:320,height:760}});
 await motion.goto(base+'/projects/nrth-health');await motion.locator('[data-scenario-choice]').nth(2).click();
 check(await motion.locator('[data-worked-example]').getAttribute('data-example-settled')==='true','Reduced motion changes geometry without an animated transition.');
 check(await motion.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'The page reflows at 320px without horizontal overflow.');
 await page.goto(base+'/projects/nrth-chemicals');
 await page.evaluate(()=>window.dispatchEvent(new CustomEvent('nrth:motion',{detail:{paused:true}})));
 await page.locator('[data-scenario-choice]').nth(2).click();
 check(await page.locator('[data-worked-example]').getAttribute('data-example-settled')==='true','A motion pause retains functional scenario input.');
 check(errors.length===0,'No browser exceptions: '+errors.join('; '));
 fs.writeFileSync(path.join(artifact,'results.json'),JSON.stringify({checks,errors},null,2));
 console.log('Worked example director: '+checks+' checks passed.');await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
